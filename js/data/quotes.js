// Helper to get a quote relevant to a subject or topic
export function getRelevantQuote(subjectId, topicName) {
  // Map subject IDs to quote categories
  const subjectCategoryMap = {
    'subj_polsci': ['justice', 'governance', 'leadership'],
    'subj_envsc': ['environment', 'nature'],
    'subj_criminology': ['justice', 'law'],
    'subj_islhist': ['islamic_history', 'civilization'],
    'subj_islamiat': ['hadith', 'quran', 'knowledge'],
    'subj_current': ['global', 'leadership'],
    'subj_pakaffairs': ['pakistan', 'nation'],
    'subj_essay': ['knowledge', 'motivation'],
    'subj_precis': ['knowledge', 'language'],
    'subj_gsa': ['knowledge', 'science'],
    'subj_sindhi': ['knowledge', 'culture']
  };
  
  const relevantCategories = subjectCategoryMap[subjectId] || ['general', 'motivation'];
  const relevant = QUOTES_DB.filter(q => q.categories.some(c => relevantCategories.includes(c)));
  
  if (relevant.length === 0) {
    const general = QUOTES_DB.filter(q => q.categories.includes('general') || q.categories.includes('motivation'));
    return general[Math.floor(Math.random() * general.length)];
  }
  
  // Use date-based seed for consistent daily quote
  const today = new Date();
  const seed = today.getFullYear() * 10000 + (today.getMonth() + 1) * 100 + today.getDate();
  return relevant[seed % relevant.length];
}
